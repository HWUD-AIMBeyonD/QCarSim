#!/usr/bin/env python3
"""Build the Nav2 grid map and the Gazebo world from the hardware map.

The hardware map (new_map.pgm) was built by Cartographer on the real QCar.
Gazebo world == map frame, and map (0, 0) is where the real car started.

A wall cell is any non-free cell (occupied OR unknown) that touches a free
cell (8-neighbourhood). Using only the occupied cells would leave ~500 gaps
where the real lidar saw the wall only partially. This closes the corridor
exactly along the edge of the real driveable area.

--grid-out writes those walls as a clean occupancy grid for Nav2.
--walls picks what goes into the world: nothing (default -- the real walls are
cardboard the car sometimes cuts through, and the KPIs don't measure obstacle
avoidance), visual-only floor lines, or solid walls. Wall cells are merged
into boxes (horizontal runs, then identical runs stacked vertically).

Usage:
    python3 generate_world_from_map.py <map.yaml> <out.sdf>
        [--grid-out <grid.yaml>] [--walls none|lines|solid] [--wall-height 0.4]
"""

import argparse
import os

import numpy as np
import yaml


def read_pgm(path):
    with open(path, 'rb') as f:
        data = f.read()
    # P5 header: magic, width, height, maxval, separated by whitespace/comments
    tokens = []
    i = 0
    while len(tokens) < 4:
        while data[i:i + 1].isspace():
            i += 1
        if data[i:i + 1] == b'#':
            while data[i:i + 1] not in (b'\n', b''):
                i += 1
            continue
        start = i
        while not data[i:i + 1].isspace():
            i += 1
        tokens.append(data[start:i])
    if tokens[0] != b'P5':
        raise ValueError('only binary PGM (P5) is supported')
    width, height, maxval = int(tokens[1]), int(tokens[2]), int(tokens[3])
    if maxval > 255:
        raise ValueError('16-bit PGM not supported')
    i += 1  # single whitespace after maxval
    pixels = np.frombuffer(data[i:i + width * height], dtype=np.uint8)
    return pixels.reshape((height, width))


# Driveable = cells the lidar actually saw as free (254 in a map_saver PGM).
# Deliberately NOT the yaml's free_thresh: new_map.yaml has free_thresh 0.25,
# which also classifies unknown grey (205 -> 0.196) as free.
FREE_MAX_P = 0.1


def free_mask(img, meta):
    p = (255 - img.astype(float)) / 255.0
    if meta.get('negate', 0):
        p = img.astype(float) / 255.0
    return p < FREE_MAX_P


def wall_mask(img, meta):
    free = free_mask(img, meta)

    near_free = np.zeros_like(free)
    padded = np.pad(free, 1)
    h, w = free.shape
    for dr in (-1, 0, 1):
        for dc in (-1, 0, 1):
            near_free |= padded[1 + dr:1 + dr + h, 1 + dc:1 + dc + w]
    return near_free & ~free


def merge_boxes(mask):
    """Return (row0, row1, col0, col1) inclusive rectangles covering mask."""
    runs_by_row = []
    for r in range(mask.shape[0]):
        runs = []
        c = 0
        cols = mask.shape[1]
        while c < cols:
            if mask[r, c]:
                c0 = c
                while c < cols and mask[r, c]:
                    c += 1
                runs.append((c0, c - 1))
            else:
                c += 1
        runs_by_row.append(runs)

    boxes = []
    open_boxes = {}  # (c0, c1) -> row0
    for r, runs in enumerate(runs_by_row):
        current = set(runs)
        for key in list(open_boxes):
            if key not in current:
                boxes.append((open_boxes.pop(key), r - 1) + key)
        for key in runs:
            open_boxes.setdefault(key, r)
    last = len(runs_by_row) - 1
    for key, r0 in open_boxes.items():
        boxes.append((r0, last) + key)
    return boxes


