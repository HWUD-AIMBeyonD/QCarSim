#!/usr/bin/env python3
"""Generate the sim param files from the hardware (Dashing) param files.

Every planner/controller/costmap value is taken from the hardware repo, so the
sim never runs a different tuning. Only the layout changes, because Jazzy
differs in three ways:

  * costmaps use `plugins: [...]` instead of `plugin_names` / `plugin_types`
  * the ported servers host their costmaps at /global_costmap/global_costmap
    and /local_costmap/local_costmap, so the costmap blocks move to those keys
  * use_sim_time is true

bt_navigator is Jazzy's, so its block is sim-specific (see BT_NAVIGATOR).

Two planner variants, each read from its own hardware branch with
`git show <branch>:<path>` (read-only; works whatever branch is checked out):

  * hybrid (branch `planner`): custom hybrid_planner_server with its internal
    global costmap.
  * navfn  (branch `main`): Dashing's stock navfn_planner, which plans on the
    standalone /global_costmap/costmap. The sim runs Jazzy's planner_server +
    NavfnPlanner with that same costmap block (same tolerance/use_astar/
    allow_unknown).

The hardware's world_model and recoveries_server are not generated: Jazzy has
no world_model, and the plan-once behaviour tree never calls a recovery.

Output: config/hw/nav2_params_<controller>_<planner>.yaml

Usage:
    python3 sync_hw_params.py [--hw-repo ~/Documents/qcar] [--out-dir config/hw] [--check]

--check writes nothing and exits 1 if the files on disk are out of date.
"""

import argparse
import copy
import os
import subprocess
import sys

import yaml

CONTROLLERS = {
    'rpp': 'nav2_params_rpp.yaml',
    'stanley': 'nav2_params_stanley.yaml',
    'vector': 'nav2_params_vector_pursuit.yaml',
}

BT_NAVIGATOR = {
    'use_sim_time': True,
    'global_frame': 'map',
    'robot_base_frame': 'base',
    'odom_topic': '/odom',
    'bt_loop_duration': 10,
    'default_server_timeout': 20,
    # Jazzy checks for the action servers when bt_navigator activates (Dashing
    # only checked on the first tick); give the non-lifecycle servers time to start.
    'wait_for_service_timeout': 20000,
    'navigators': ['navigate_to_pose'],
    'navigate_to_pose': {'plugin': 'nav2_bt_navigator::NavigateToPoseNavigator'},
    # Filled in by the launch file with the installed path.
    'default_nav_to_pose_bt_xml': '',
}

# planner -> hardware branch holding that planner's param files
PLANNERS = {
    'hybrid': 'planner',
    'navfn': 'main',
}

HW_CONFIG = 'src/qcar_nav2_bringup/config/'

HEADER = """\
# GENERATED by qcar_nav2_bringup/scripts/sync_hw_params.py from
# <hardware repo> {ref}:{src}
# Do not edit by hand: change the hardware file and re-run the script.
"""


def jazzy_costmap(block):
    out = copy.deepcopy(block)
    out['plugins'] = out.pop('plugin_names')
    out.pop('plugin_types', None)
    out['use_sim_time'] = True
    for name in out['plugins']:
        if 'plugin' not in out[name]:
            raise ValueError('costmap layer {} has no plugin type'.format(name))
    return out


def convert(hw, planner_type):
    if planner_type == 'hybrid':
        planner = copy.deepcopy(hw['hybrid_planner_server']['ros__parameters'])
        global_costmap = jazzy_costmap(planner.pop('global_costmap'))
        planner['use_sim_time'] = True
        planner_block = {'hybrid_planner_server': {'ros__parameters': planner}}
    else:
        navfn = copy.deepcopy(hw['navfn_planner']['ros__parameters'])
        navfn.pop('use_sim_time', None)
        navfn['plugin'] = 'nav2_navfn_planner::NavfnPlanner'
        planner_block = {'planner_server': {'ros__parameters': {
            'use_sim_time': True,
            'planner_plugins': ['GridBased'],
            'GridBased': navfn,
        }}}
        global_costmap = jazzy_costmap(hw['global_costmap']['costmap']['ros__parameters'])

    controller = copy.deepcopy(hw['controller_server']['ros__parameters'])
    local_costmap = jazzy_costmap(controller.pop('local_costmap'))
    controller['use_sim_time'] = True

    out = planner_block
    out.update({
        'global_costmap': {'global_costmap': {'ros__parameters': global_costmap}},
        'controller_server': {'ros__parameters': controller},
        'local_costmap': {'local_costmap': {'ros__parameters': local_costmap}},
        'bt_navigator': {'ros__parameters': copy.deepcopy(BT_NAVIGATOR)},
    })
    return out


def render(hw_repo, ref, hw_name, planner_type):
    src = HW_CONFIG + hw_name
    text = subprocess.check_output(['git', '-C', hw_repo, 'show', '{}:{}'.format(ref, src)])
    hw = yaml.safe_load(text)
    body = yaml.safe_dump(convert(hw, planner_type), sort_keys=False, default_flow_style=None)
    return HEADER.format(ref=ref, src=src) + body


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--hw-repo', default=os.path.expanduser('~/Documents/qcar'))
    parser.add_argument('--out-dir', default=os.path.join(here, '..', 'config', 'hw'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    stale = []
    jobs = [(p, ref, c, f) for p, ref in PLANNERS.items() for c, f in CONTROLLERS.items()]
    for planner_type, ref, name, hw_name in jobs:
        text = render(args.hw_repo, ref, hw_name, planner_type)
        out_file = os.path.join(args.out_dir, 'nav2_params_{}_{}.yaml'.format(name, planner_type))
        current = open(out_file).read() if os.path.exists(out_file) else None
        if args.check:
            if current != text:
                stale.append(out_file)
        elif current != text:
            with open(out_file, 'w') as f:
                f.write(text)
            print('Wrote', os.path.normpath(out_file))

    if stale:
        print('Out of date (re-run sync_hw_params.py):')
        for f in stale:
            print('  ' + os.path.normpath(f))
        sys.exit(1)


if __name__ == '__main__':
    main()
