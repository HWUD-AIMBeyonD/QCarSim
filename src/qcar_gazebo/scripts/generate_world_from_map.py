def write_grid_map(img, meta, wall, out_yaml):
    """Write a clean Nav2 occupancy grid with the same closed walls.

    free 254 / wall 0 / everything else 205 (unknown). free_thresh is 0.196,
    so unknown grey stays unknown in direct_map_publisher and map_server
    (the raw new_map.yaml uses 0.25, which turns unknown into free).
    """
    free = free_mask(img, meta)
    grid = np.full(img.shape, 205, dtype=np.uint8)
    grid[free] = 254
    grid[wall] = 0

    out_pgm = os.path.splitext(out_yaml)[0] + '.pgm'
    with open(out_pgm, 'wb') as f:
        f.write('P5\n{} {}\n255\n'.format(grid.shape[1], grid.shape[0]).encode())
        f.write(grid.tobytes())

    grid_meta = {
        'image': os.path.basename(out_pgm),
        'mode': 'trinary',
        'resolution': float(meta['resolution']),
        'origin': [float(v) for v in meta['origin']],
        'negate': 0,
        'occupied_thresh': 0.65,
        'free_thresh': 0.196,
    }
    with open(out_yaml, 'w') as f:
        f.write('# GENERATED by qcar_gazebo/scripts/generate_world_from_map.py\n')
        yaml.safe_dump(grid_meta, f, sort_keys=False, default_flow_style=None)
    print('Wrote {} + {} ({} free, {} wall cells)'.format(
        out_yaml, os.path.basename(out_pgm), int(free.sum()), int(wall.sum())))


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('map_yaml')
    parser.add_argument('out_sdf')
    parser.add_argument('--grid-out', metavar='MAP_YAML',
                        help='also write a clean Nav2 occupancy grid (yaml + pgm)')
    parser.add_argument('--walls', choices=['none', 'lines', 'solid'], default='none',
                        help='none: no walls (default; the car can cut through, like the '
                             'real cardboard). lines: visual-only floor markings, no '
                             'collision, too low for the lidar. solid: collidable walls.')
    parser.add_argument('--wall-height', type=float, default=0.4)
    args = parser.parse_args()

    with open(args.map_yaml) as f:
        meta = yaml.safe_load(f)
    image = meta['image']
    if not os.path.isabs(image):
        image = os.path.join(os.path.dirname(os.path.abspath(args.map_yaml)), image)
    img = read_pgm(image)

    res = float(meta['resolution'])
    ox, oy = float(meta['origin'][0]), float(meta['origin'][1])
    height = img.shape[0]

    wall = wall_mask(img, meta)
    if args.grid_out:
        write_grid_map(img, meta, wall, args.grid_out)

    boxes = merge_boxes(wall) if args.walls != 'none' else []
    wall_h = 0.002 if args.walls == 'lines' else args.wall_height

    out = [HEADER.format(map_name=os.path.basename(args.map_yaml))]
    if boxes:
        out.append(WALLS_OPEN)
        for i, (r0, r1, c0, c1) in enumerate(boxes):
            # image row 0 is the TOP of the map (max y)
            x0 = ox + c0 * res
            x1 = ox + (c1 + 1) * res
            y0 = oy + (height - 1 - r1) * res
            y1 = oy + (height - r0) * res
            box = dict(i=i, x=(x0 + x1) / 2, y=(y0 + y1) / 2, z=wall_h / 2,
                       sx=x1 - x0, sy=y1 - y0, sz=wall_h)
            if args.walls == 'solid':
                out.append(COLLISION.format(**box))
            out.append(VISUAL.format(**box))
        out.append(WALLS_CLOSE)

    rows, cols = np.where(free_mask(img, meta))
    cx = ox + (cols.mean() + 0.5) * res
    cy = oy + (height - rows.mean() - 0.5) * res
    out.append(FOOTER.format(cx=cx, cy=cy - 3.0))

    with open(args.out_sdf, 'w') as f:
        f.write(''.join(out))
    print('Wrote {} (walls: {}, {} boxes)'.format(args.out_sdf, args.walls, len(boxes)))


if __name__ == '__main__':
    main()
